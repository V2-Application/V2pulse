# Words that stay upper-case in generated column labels.
ACRONYMS = {"ID", "MC", "MRP", "RDC", "DC", "SLOC", "UOM", "HSN", "GL", "SAP", "RFC", "GSTIN", "PSF", "PTL", "MSA", "FA",
            "ZM", "RM", "CM", "TCX", "SRM", "MVGR", "FG", "NOA", "HO", "PIN", "HEX", "NSO", "SOMPS"}

T, N, D, TS, B = "text", "number", "date", "datetime", "bool"


def label(col: str) -> str:
    words = col.lower().split("_")
    out = [w.upper() if w.upper() in ACRONYMS else w for w in words]
    return " ".join(out)[:1].upper() + " ".join(out)[1:]


def C(name, typ=T, src=None, label_=None, key=False, search=None, hidden=False):
    """One column: output name, type, source column/expression (default = same name)."""
    return {"name": name, "type": typ, "src": src or name, "label": label_ or label(name), "key": key,
            "searchable": typ == T if search is None else search, "filterable": True, "hidden": hidden}


