def snowflake_block(include_bi: bool = True) -> str:
    """Every master view (and the dataset views) as ONE Snowflake statement, so it runs completely however it
    is pasted into a worksheet. Generated by: python -m pulse.cli views-sql"""
    stmts = [view_sql(m) for m in MASTERS if m.get("source")]
    if include_bi:
        from . import bi_catalog
        stmts += [bi_catalog.view_sql(d) for d in bi_catalog.DATASETS]
    stmts.append("grant select on all views in schema V2RETAIL.PULSE to role PULSE_SVC_ROLE;")
    body = "\n".join(stmts)
    assert "$$" not in body
    return ("-- V2Pulse: all curated views (%d) in ONE statement. Paste into a Snowsight SQL worksheet as ACCOUNTADMIN\n"
            "-- and press Run once. Safe to re-run. The result reads: V2Pulse views created: %d\n"
            "EXECUTE IMMEDIATE $$\nBEGIN\n%s\nRETURN 'V2Pulse views created: %d';\nEND;\n$$;\n"
            % (len(stmts) - 1, len(stmts) - 1, body, len(stmts) - 1))

IDENT = re.compile(r"^[A-Z_][A-Z0-9_]*$")


def source_object(m: dict) -> str:
    return "%s.%s" % (PULSE, m["view"])


def catalog_columns(m: dict) -> list[dict]:
    return [{k: c[k] for k in ("name", "label", "type", "key", "searchable", "filterable", "hidden")} for c in m["columns"]]


def view_sql(m: dict) -> str | None:
    """CREATE VIEW for one master, or None when it reads an existing PULSE view."""
    if not m.get("source"):
        return None
    for c in m["columns"]:
        assert IDENT.match(c["name"]), c["name"]
    cols = ",\n  ".join(("%s as %s" % (c["src"], c["name"])) if c["src"] != c["name"] else c["name"] for c in m["columns"])
    src = m["source"] if m["source"].startswith(SRC + ".") else "%s.%s" % (SRC, m["source"])
    where = "\nwhere %s" % m["where"] if m.get("where") else ""
    return ("create or replace view %s.%s\n  comment = 'V2Pulse master: %s'\nas select\n  %s\nfrom %s%s;"
            % (PULSE, m["view"], m["name"].replace("'", "''"), cols, src, where))


def snowflake_sql() -> str:
    parts = ["-- V2Pulse masters: PART C. Curated views in V2RETAIL.PULSE that the Masters library reads.",
             "-- Generated from pulse/modules/masters_catalog.py (python -m pulse.cli masters-sql). Do not edit by hand.",
             "-- Run as a role that can read the source tables and create views in V2RETAIL.PULSE",
             "-- (DATA_PLATFORM_ADMIN or ACCOUNTADMIN). Safe to re-run.", "",
             "use role ACCOUNTADMIN;", "use warehouse COMPUTE_WH;", ""]
    for m in MASTERS:
        sql = view_sql(m)
        if sql:
            parts += ["-- %s (%s)" % (m["name"], m["code"]), sql, ""]
    parts += ["-- PULSE_SVC_ROLE already has select on future views in V2RETAIL.PULSE; this covers views that existed.",
              "grant select on all views in schema V2RETAIL.PULSE to role PULSE_SVC_ROLE;", ""]
    return "\n".join(parts)
